# Тревога из эфира для live_tail.sh. Под тестом — test_alert.sh.
#
# 💣 28.10 распознавания не было полтора часа, и никто не узнал: в чат не
# приходило ни блоков, ни ошибок. Тишина в чате выглядит точно так же, как
# «эфир ещё не начался», — именно это и стоило записи 1:1.
#
# Решение Sergey 28.10: «если какой-то алерт и требуется внимания… пока можно
# ограничиться просто отправкой в VK assistant». Голосом в эфире — никогда
# (его фидбек 14.09), поэтому канал — voice-reply (текст), не voice-reply-both.
#
# alert_due <now> <last> <every> → "1", если тревогу можно отправить
# alert_fire <текст>             → отправить в VK (всегда rc 0)
# alert_vk_default               → имя бинаря канала по умолчанию

alert_vk_default() { printf 'voice-reply'; }

alert_due() {
  local now=$1 last=$2 every=$3
  # Отказ повторяется каждый чанк: без окна Sergey получал бы сообщение раз в
  # 20 секунд. Окно на событие, а не на канал — ключи событий держит вызывающий.
  [ "$every" -le 0 ] && { echo 1; return 0; }
  [ $((now - last)) -ge "$every" ] && echo 1
  return 0
}

alert_fire() {
  local text=$1
  # ⚠️ Тревога — уведомление, а не часть транскрипции: нет сети, нет токена,
  # нет бинаря — хвост продолжает резать чанки. Поэтому rc всегда 0.
  "${ALERT_VK_BIN:-$(alert_vk_default)}" "${ALERT_PEER:-360258728}" "$text" \
    >/dev/null 2>&1 || true
  return 0
}
