#!/usr/bin/env bash
# Тест проверки уровня дорожек. Инцидент 28.10 (1:1 с руководителем): микрофон
# в OBS писал пустой источник — средний уровень −40 dB, пики-щелчки до 0 dB,
# речи нет. Узнали об этом ПОСЛЕ эфира, реплики Sergey потеряны целиком, хотя
# один замер в начале дал бы минуту на починку. Ровно та же картина была 22.10
# с системным звуком: устройство в сцене есть, звук в него не идёт.
# Пороги — решение Sergey 28.10: ниже −45 мёртвая, −45…−35 предупреждение.
# Старт НЕ блокируется (его же решение): ложное срабатывание не должно стоить
# записи эфира.
#
#   ./test_levels.sh
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/lib_levels.sh"

FAIL=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; FAIL=1; }
eq() { [ "$3" = "$2" ] && ok "$1 = '$2'" || bad "$1: хотел '$2', получил '$3'"; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ── вердикт по уровню ───────────────────────────────────────────────────────
# Замеры живых дорожек за три дня: −25.1, −25.7, −31.9, −32.9, −38.3 dB.
eq "обычный эфир"            "ok"    "$(level_verdict -25.7)"
eq "тихо, но слышно"         "ok"    "$(level_verdict -32.9)"
# −38.3 жил, но близко к границе: предупреждение, не отказ.
eq "на границе — тихая"      "quiet" "$(level_verdict -38.3)"
# Пустой источник 28.10 — ровно этот случай.
eq "пустой источник 28.10"   "quiet" "$(level_verdict -40.1)"
eq "мёртвая дорожка 22.10"   "dead"  "$(level_verdict -91)"
eq "ровно −45 — мёртвая"     "dead"  "$(level_verdict -45)"
eq "ровно −35 — норма"       "ok"    "$(level_verdict -35)"
# Дорожки нет / ffmpeg ничего не сказал — это не «мёртвая», это «не знаю»:
# пугать Sergey тревогой на пустом месте нельзя.
eq "нет замера"              "absent" "$(level_verdict '')"
eq "мусор вместо числа"      "absent" "$(level_verdict 'N/A')"
eq "-inf (абсолютная тишина)" "dead"  "$(level_verdict '-inf')"

# ── человеческая строка для шапки конспекта ─────────────────────────────────
# Шапка — единственное место, где это увидит человек при разборе записи.
case "$(level_line 1 -25.7 ok)" in
  *"дорожка 1"*"-25.7"*) ok "строка шапки содержит номер и уровень" ;;
  *) bad "строка шапки бесполезна: $(level_line 1 -25.7 ok)" ;;
esac
case "$(level_line 2 -40.1 quiet)" in
  *"тих"*) ok "тихая дорожка названа тихой" ;;
  *) bad "нет пометки о тишине: $(level_line 2 -40.1 quiet)" ;;
esac
case "$(level_line 2 -91 dead)" in
  *"мёртв"*) ok "мёртвая дорожка названа мёртвой" ;;
  *) bad "нет пометки о смерти: $(level_line 2 -91 dead)" ;;
esac

# ── замер на хосте ──────────────────────────────────────────────────────────
# ssh подменяем: тест не ходит на мак и не зависит от наличия записи.
FAKE="$TMP/fake-ssh"
cat > "$FAKE" <<'SH'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "$SSH_LOG"
cat "$SSH_OUT"
SH
chmod +x "$FAKE"; export SSH_LOG="$TMP/ssh.log" SSH_OUT="$TMP/ssh.out"

# Настоящий вывод volumedetect (ffmpeg пишет его в stderr, строкой среди прочего).
cat > "$SSH_OUT" <<'OUT'
[Parsed_volumedetect_0 @ 0xab0dcdec0] mean_volume: -25.7 dB
[Parsed_volumedetect_0 @ 0xab0dcdec0] max_volume: -0.1 dB
OUT
eq "уровень вынут из вывода ffmpeg" "-25.7" \
  "$(LEVELS_SSH_BIN="$FAKE" levels_measure mac-work '/Users/s/Movies/a.mov' 1 60)"
CMD="$(tail -1 "$SSH_LOG")"
case "$CMD" in
  # Дорожка адресуется как 0:a:N (нумерация с нуля) — иначе меряли бы не то.
  *"-map 0:a:0"*volumedetect*) ok "меряется запрошенная дорожка" ;;
  *) bad "не та команда замера: $CMD" ;;
esac
case "$CMD" in
  *"-t 60"*) ok "меряется окно, а не весь файл" ;;
  *) bad "нет ограничения по времени: $CMD" ;;
esac

# Дорожки нет — ffmpeg не напечатает mean_volume. Пустой замер, не ноль.
: > "$SSH_OUT"
eq "нет дорожки — пустой замер" "" \
  "$(LEVELS_SSH_BIN="$FAKE" levels_measure mac-work '/x.mov' 2 60)"

[ "$FAIL" -eq 0 ] && echo "все проверки зелёные" || { echo "есть красные"; exit 1; }
