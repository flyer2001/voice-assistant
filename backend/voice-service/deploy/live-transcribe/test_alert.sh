#!/usr/bin/env bash
# Тест тревоги. Инцидент 28.10: распознавания не было полтора часа, и об этом
# никто не узнал — в чат не приходило ни блоков, ни ошибок, а тишина в чате
# неотличима от «эфир ещё не начался». Решение Sergey 28.10: алерт текстом в VK
# («можно ограничиться просто отправкой в VK assistant»), голосом в эфире —
# никогда (его фидбек 14.09).
# Контракт: событие даёт ровно одну тревогу, повтор в окне молчит, падение
# канала не роняет хвост.
#
#   ./test_alert.sh
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/lib_alert.sh"

FAIL=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; FAIL=1; }
eq() { [ "$3" = "$2" ] && ok "$1 = '$2'" || bad "$1: хотел '$2', получил '$3'"; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ── дедупликация ────────────────────────────────────────────────────────────
# Отказ распознавания повторяется каждый чанк. Без окна Sergey получил бы по
# сообщению в VK каждые 20 секунд — это не тревога, это флуд.
eq "первая тревога проходит"   "1" "$(alert_due 1000 0 600)"
eq "повтор в окне молчит"      ""  "$(alert_due 1100 1000 600)"
eq "по краю окна проходит"     "1" "$(alert_due 1600 1000 600)"
eq "спустя окно проходит"      "1" "$(alert_due 2000 1000 600)"
# Разные события не глушат друг друга: ключ события свой у каждого.
eq "every=0 — без дедупа"      "1" "$(alert_due 1001 1000 0)"

# ── канал VK ────────────────────────────────────────────────────────────────
FAKE="$TMP/fake-vk"
cat > "$FAKE" <<'SH'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "$VK_LOG"
exit "${VK_RC:-0}"
SH
chmod +x "$FAKE"; export VK_LOG="$TMP/vk.log"

ALERT_VK_BIN="$FAKE" alert_fire "распознавания нет: HTTP 000 два чанка подряд"
SENT="$(tail -1 "$VK_LOG")"
case "$SENT" in
  # Адресат из решения Sergey 28.10; текст уходит дословно, без TTS-обёртки.
  "360258728 распознавания нет: HTTP 000 два чанка подряд") ok "в VK ушёл адресат и текст" ;;
  *) bad "в VK ушло не то: $SENT" ;;
esac

# Голос в эфире запрещён: voice-reply-both озвучивает, voice-reply — нет.
# Проверяем, что по умолчанию зовётся именно текстовый.
eq "канал по умолчанию текстовый" "voice-reply" "$(alert_vk_default)"

ALERT_VK_BIN="$FAKE" ALERT_PEER=42 alert_fire "другой адресат"
case "$(tail -1 "$VK_LOG")" in
  "42 другой адресат") ok "адресат переопределяется" ;;
  *) bad "адресат не переопределился: $(tail -1 "$VK_LOG")" ;;
esac

# ── падение канала ──────────────────────────────────────────────────────────
# Нет сети, нет токена, нет бинаря — хвост всё равно должен продолжать резать
# чанки: тревога это уведомление, а не часть транскрипции.
if VK_RC=1 ALERT_VK_BIN="$FAKE" alert_fire "канал лежит"; then
  ok "падение VK не считается ошибкой хвоста"
else
  bad "падение VK уронило бы хвост (rc≠0)"
fi
if ALERT_VK_BIN=/nonexistent/voice-reply alert_fire "бинаря нет"; then
  ok "отсутствие бинаря не роняет хвост"
else
  bad "отсутствие бинаря уронило бы хвост"
fi

[ "$FAIL" -eq 0 ] && echo "все проверки зелёные" || { echo "есть красные"; exit 1; }
