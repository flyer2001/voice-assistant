#!/usr/bin/env bash
# Тест пульса держателя машины. Инцидент 28.10: ubuntu-home уснула трижды за
# день посреди эфиров. Причина — `with-host.sh --hold` создаёт держатель в
# ~/.agentops/holds ОДИН раз, а сторож простоя на хосте считает его протухшим
# через KEEPAWAKE_TTL=3600. Эфир шёл четвёртый час, держатель умер на первом,
# машина законно уснула, живого распознавания не было: 1:1 с руководителем
# пришлось догонять из файла, реплики Sergey потеряны целиком.
# Контракт: пока хвост режет чанки, держатель обновляется; хвост встал —
# держатель снят, машина свободна уснуть.
#
#   ./test_hold.sh
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/lib_hold.sh"

FAIL=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; FAIL=1; }
eq() {  # eq <что> <ожидание> <получено>
  [ "$3" = "$2" ] && ok "$1 = '$2'" || bad "$1: хотел '$2', получил '$3'"
}

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Имя держателя привязано к сессии: два эфира на одной машине не должны
# затирать держатель друг друга, и по имени видно, кто машину одолжил.
eq "имя держателя" "voice-live-abc123" "$(hold_id abc123)"
eq "имя без sid"   "voice-live-noid"   "$(hold_id '')"

# ── когда пора обновлять ────────────────────────────────────────────────────
# Пульс дешёвый (замер 29.10: ssh touch 1.77 и 1.86 с), но дёргать его на
# каждый чанк незачем — хватает раза в VOICE_HOLD_EVERY секунд.
eq "первый раз — сразу"       "1" "$(hold_due 1000 0 300)"
eq "окно не прошло — молчим"  ""  "$(hold_due 1200 1000 300)"
eq "ровно окно — пора"        "1" "$(hold_due 1300 1000 300)"
eq "окно прошло — пора"       "1" "$(hold_due 1600 1000 300)"
# Выключатель: пульс не нужен, когда машину держит кто-то другой.
eq "every=0 — пульс выключен" "" "$(hold_due 9999 0 0)"

# ── что уходит на хост ──────────────────────────────────────────────────────
# ssh подменяем: тест не должен ходить по сети и зависеть от спящей машины.
FAKE="$TMP/fake-ssh"
cat > "$FAKE" <<'SH'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "$FAKE_LOG"
exit "${FAKE_RC:-0}"
SH
chmod +x "$FAKE"
export FAKE_LOG="$TMP/ssh.log"

HOLD_SSH_BIN="$FAKE" hold_touch ubuntu-home voice-live-t1
CMD="$(tail -1 "$FAKE_LOG")"
case "$CMD" in
  *ubuntu-home*) ok "пульс идёт на нужный хост" ;;
  *) bad "хост потерян: $CMD" ;;
esac
case "$CMD" in
  # Каталог создаём сами: на свежей машине holds может не быть, и тогда touch
  # упал бы молча, а машина уснула бы под работой.
  *"mkdir -p"*".agentops/holds"*"touch"*"voice-live-t1"*) ok "mkdir + touch держателя" ;;
  *) bad "не та команда: $CMD" ;;
esac

# Снятие держателя — обязательная часть: забытый держатель не даст машине
# уснуть никогда (ровно это нашли на хосте 29.10 — чужой файл от 27.10).
HOLD_SSH_BIN="$FAKE" hold_drop ubuntu-home voice-live-t1
CMD="$(tail -1 "$FAKE_LOG")"
case "$CMD" in
  *"rm -f"*"voice-live-t1"*) ok "держатель снимается" ;;
  *) bad "держатель не снят: $CMD" ;;
esac

# ── отказ ssh не роняет эфир ────────────────────────────────────────────────
# Машина могла уснуть ровно сейчас. Пульс не важнее транскрипции: он сообщает
# код возврата, но не прерывает хвост.
if FAKE_RC=255 HOLD_SSH_BIN="$FAKE" hold_touch ubuntu-home voice-live-t1; then
  bad "упавший ssh отдал успех"
else
  ok "упавший ssh отдаёт ненулевой код"
fi

[ "$FAIL" -eq 0 ] && echo "все проверки зелёные" || { echo "есть красные"; exit 1; }
