#!/usr/bin/env bash
# Тест записи куска в конспект. Главное, что проверяем, — текст эфира не
# теряется ни в одной ветке: фильтр эха (26.10, свой TTS вернулся через
# микрофон с командами «коммить» и «пушить») помечает блок, но не удаляет его.
#
#   ./test_echo_wiring.sh
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/lib_echo.sh"

FAIL=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; FAIL=1; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
TTS="$TMP/voice-out"; mkdir -p "$TTS"

LONG_TTS="Сергей, последний слой со снапшотом застейджен, проверки прошли. Коммить, описание пул реквеста в чате. Перед пулом нужен ребейз на девелоп."
HEARD="Если хочешь, надо обсудить контракт. Сергей, последний слой со снапшотом застейджен, проверки прошли. Комить, описание пул, реквесты в чате."
SPEECH="Я докатил в пятницу задачку про возврат минзаказа в кнопках. Вмержено и раскачано на проде под АБ."

python3 - "$TTS" "$LONG_TTS" <<'PY'
import json, sys
json.dump({"client_id": "mac-work", "text": sys.argv[2]},
          open(sys.argv[1] + "/mac-work-fixture.json", "w"))
PY

WHY_ECHO="$(echo_verdict "$HEARD" "$TTS")"
[ -n "$WHY_ECHO" ] && ok "эхо распознано: $WHY_ECHO" || bad "эхо не распознано"
WHY_SPEECH="$(echo_verdict "$SPEECH" "$TTS")"
[ -z "$WHY_SPEECH" ] && ok "живая речь не помечена" || bad "речь принята за эхо: $WHY_SPEECH"

# Эхо: в конспекте есть под меткой, в блок не уходит
OUT="$TMP/live.md"
BLOCK="$(emit_block "$OUT" "00:06:30" "эфир" "$HEARD" "$WHY_ECHO")"
[ -z "$BLOCK" ] && ok "эхо не уходит в блок для сессии" || bad "эхо уехало в блок"
grep -qF "$HEARD" "$OUT" && ok "текст эха сохранён в конспекте" \
  || bad "ТЕКСТ ПОТЕРЯН — конспект единственная копия"
grep -q "эхо TTS" "$OUT" && ok "метка поставлена" || bad "нет метки"

# Эфир: уходит и в конспект, и в блок, дословно
BLOCK="$(emit_block "$OUT" "00:07:00" "эфир" "$SPEECH" "")"
[ "$BLOCK" = "эфир: $SPEECH" ] && ok "речь уходит в блок дословно с меткой дорожки" \
  || bad "блок искажён: $BLOCK"
grep -qF "$SPEECH" "$OUT" && ok "речь в конспекте" || bad "речь не записана"

# Одна дорожка — без метки спикера (в миксе «эфир:» перед каждой строкой шум)
BLOCK="$(emit_block "$OUT" "00:07:30" "" "$SPEECH" "")"
[ "$BLOCK" = "$SPEECH" ] && ok "без метки дорожки блок идёт как есть" \
  || bad "одна дорожка: блок искажён"

# Фильтр недоступен — пишем как эфир, а не роняем транскрипцию
WHY="$(ECHO_FILTER_BIN=/nonexistent/echo_filter.py echo_verdict "$HEARD" "$TTS")"
[ -z "$WHY" ] && ok "нет фильтра — текст считается эфиром" || bad "сломанный фильтр съел эфир"

# Фильтр падает с ошибкой — то же самое
BROKEN="$TMP/broken.py"; printf 'import sys\nsys.exit(9)\n' > "$BROKEN"
WHY="$(ECHO_FILTER_BIN="$BROKEN" echo_verdict "$HEARD" "$TTS")"
[ -z "$WHY" ] && ok "фильтр упал — текст считается эфиром" || bad "падение фильтра пометило эфир"

[ "$FAIL" -eq 0 ] && echo "все проверки зелёные" || { echo "есть красные"; exit 1; }
