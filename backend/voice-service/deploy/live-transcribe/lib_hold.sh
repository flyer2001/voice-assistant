# Пульс держателя машины для live_tail.sh. Под тестом — test_hold.sh.
#
# 💣 28.10 ubuntu-home уснула трижды за день посреди эфиров, и каждый раз
# «удержание» выглядело живым. Разбор нашёл два независимых механизма:
#   1. `with-host.sh --hold` создаёт файл в ~/.agentops/holds ОДИН раз и
#      больше его не трогает, а сторож простоя на хосте считает держатель
#      протухшим через KEEPAWAKE_TTL=3600 (по mtime). Эфир шёл четвёртый час —
#      держатель умер на первом.
#   2. Сторож считает потребителем established TCP на портах резидентов и
#      смотрит раз в 5 минут; хвост делает короткий curl на чанк и закрывает
#      соединение, так что для сторожа эфир = тишина.
# Отсюда пульс: пока режем чанки, обновляем mtime держателя сами.
#
# ⚠️ Пульс НЕ важнее транскрипции: любой отказ ssh отдаётся кодом возврата, но
# хвост не прерывает. Машина, уснувшая под работой, лечится будильником
# (lib_wake.sh), а не падением эфира.
#
# hold_id <sid>                  → имя файла-держателя
# hold_due <now> <last> <every>  → "1", если пора обновлять ("" если нет)
# hold_touch <host> <id>         → создать/обновить держатель на хосте
# hold_drop <host> <id>          → снять держатель

HOLDS_DIR_REMOTE="${VOICE_HOLDS_DIR:-\$HOME/.agentops/holds}"

hold_id() {
  # Привязка к сессии: два эфира на одной машине не затирают держатель друг
  # друга, и по имени в вердикте сторожа видно, кто машину одолжил.
  printf 'voice-live-%s' "${1:-noid}"
}

hold_due() {
  local now=$1 last=$2 every=$3
  [ "$every" -le 0 ] && return 0          # выключено — кто-то держит машину сам
  [ $((now - last)) -ge "$every" ] && echo 1
  return 0
}

hold_touch() {
  local host=$1 id=$2
  # mkdir обязателен: на свежей машине holds может не быть, и touch упал бы
  # молча — а это ровно тот отказ, который 28.10 стоил полутора часов эфира.
  "${HOLD_SSH_BIN:-ssh}" -n -o BatchMode=yes -o ConnectTimeout=10 "$host" \
    "mkdir -p $HOLDS_DIR_REMOTE && touch $HOLDS_DIR_REMOTE/$id" >/dev/null 2>&1
}

hold_drop() {
  local host=$1 id=$2
  # Забытый держатель не даст машине уснуть никогда: 29.10 на хосте нашёлся
  # чужой файл от 27.10, под ним машина не спала трое суток.
  "${HOLD_SSH_BIN:-ssh}" -n -o BatchMode=yes -o ConnectTimeout=10 "$host" \
    "rm -f $HOLDS_DIR_REMOTE/$id" >/dev/null 2>&1
}
